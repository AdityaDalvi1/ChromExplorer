    public class ForensicResultRow : INotifyPropertyChanged
    {
        private string _target;
        private string _status;
        private string _confidence;
        private string _remarks;

        public string Target
        {
            get { return _target; }
            set { _target = value; OnPropertyChanged("Target"); }
        }

        public string Status
        {
            get { return _status; }
            set { _status = value; OnPropertyChanged("Status"); }
        }

        public string Confidence
        {
            get { return _confidence; }
            set { _confidence = value; OnPropertyChanged("Confidence"); }
        }

        public string Remarks
        {
            get { return _remarks; }
            set { _remarks = value; OnPropertyChanged("Remarks"); }
        }

        public event PropertyChangedEventHandler PropertyChanged;

        private void OnPropertyChanged(string propertyName)
        {
            var handler = PropertyChanged;
            if (handler != null) handler(this, new PropertyChangedEventArgs(propertyName));
        }
    }

    [Export("ForensicReport", typeof(ForensicReportView))]
    [PartCreationPolicy(CreationPolicy.NonShared)]
    public partial class ForensicReportView : UserControl
    {
        public ObservableCollection<ForensicResultRow> Results { get; }

        [Import]
        public IRegionManager RegionManager { get; set; }

        [Import]
        public ForensicReportContext ForensicContext { get; set; }

        private readonly string _connectionString = @"Data Source=source.db3;Version=3;BusyTimeout=15000;";

        public ForensicReportView()
        {
            InitializeComponent();

            Results = new ObservableCollection<ForensicResultRow>
            {
                new ForensicResultRow()
            };

            dgResults.ItemsSource = Results;

            PopulateAutoGeneratedFields();
        }

        private void PopulateAutoGeneratedFields()
        {
            var now = DateTime.Now;

            string deviceId = GetDeviceUniqueId();
            txtReportNo.Text = $"{deviceId}-{now:yyyyMMdd}-{now:HHmmss}";

            txtReceivedDate.Text = now.ToString("dd-MMM-yyyy");
            txtAnalysisDate.Text = now.ToString("dd-MMM-yyyy");

            txtAnalyst.Text = GetLoggedInAnalystFullName();
        }

        private static string GetDeviceUniqueId()
        {
            try
            {
                var mac = NetworkInterface.GetAllNetworkInterfaces()
                    .Where(nic => nic.OperationalStatus == OperationalStatus.Up &&
                                  nic.NetworkInterfaceType != NetworkInterfaceType.Loopback)
                    .Select(nic => nic.GetPhysicalAddress()?.ToString())
                    .FirstOrDefault(addr => !string.IsNullOrEmpty(addr));

                if (!string.IsNullOrEmpty(mac))
                    return mac;
            }
            catch
            {
                // fall through to fallback below
            }

            return "UNKNOWNDEVICE";
        }

        private string GetLoggedInAnalystFullName()
        {
            try
            {
                if (Application.Current != null && Application.Current.Properties.Contains("UserId") &&
                    Application.Current.Properties["UserId"] != null)
                {
                    int userId = Convert.ToInt32(Application.Current.Properties["UserId"]);

                    using (var conn = new SQLiteConnection(_connectionString))
                    {
                        conn.Open();

                        const string sql = "SELECT user_fullname FROM UserM WHERE user_id = @uid";
                        using (var cmd = new SQLiteCommand(sql, conn))
                        {
                            cmd.Parameters.AddWithValue("@uid", userId);
                            var result = cmd.ExecuteScalar();
                            if (result != null && result != DBNull.Value)
                            {
                                string fullName = result.ToString();
                                if (!string.IsNullOrWhiteSpace(fullName))
                                    return fullName;
                            }
                        }
                    }
                }
            }
            catch
            {
                // fall through to fallback below
            }

            if (Application.Current != null && Application.Current.Properties.Contains("Username") &&
                Application.Current.Properties["Username"] != null)
            {
                return Application.Current.Properties["Username"].ToString();
            }

            return Environment.UserName;
        }

        private void BtnAddResultRow_Click(object sender, RoutedEventArgs e)
        {
            Results.Add(new ForensicResultRow());
        }

        private void BtnClose_Click(object sender, RoutedEventArgs e)
        {
            CloseOverlay();
        }

        private void BtnGenerateReport_Click(object sender, RoutedEventArgs e)
        {
            // Fixed location (D:\ChromReport\Forensic by default) — no Save dialog, see
            // ReportStorage.
            string filePath = ChromExplorer.Infrastructure.ReportStorage.BuildNewReportPath(
                ChromExplorer.Infrastructure.ReportKind.Forensic);
            if (filePath == null)
                return;

            if (!ChromExplorer.Infrastructure.FileSaveGuard.CanSaveTo(filePath, "forensic report"))
                return;

            try
            {
                var data = BuildReportData();
                new ForensicPdfExporter().Export(data, filePath);

                ChromExplorer.Infrastructure.SavedFileRegistry.Record(
                    ChromExplorer.Infrastructure.SavedFileRegistry.TypeReport, filePath);

                ChromExplorer.Infrastructure.ReportStorage.ShowSavedMessage(filePath, "Forensic Report Saved");
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error generating report: " + ex.Message, "Error",
                    MessageBoxButton.OK, MessageBoxImage.Error);
            }
        }

        private ForensicReportData BuildReportData()
        {
            var data = new ForensicReportData
            {
                GeneratedDate = DateTime.Now.ToString("f"),
                ReportNo = txtReportNo.Text,
                CaseNo = txtCaseNo.Text,
                SampleDescription = txtSampleDescription.Text,
                ReceivedDate = txtReceivedDate.Text,
                AnalysisDate = txtAnalysisDate.Text,
                Analyst = txtAnalyst.Text,
                Conclusion = txtConclusion.Text,
                AnalystSignature = txtAnalystSignature.Text,
                Reviewer = txtReviewer.Text,

                ShowMassSpectrum = chkMassSpectrum.IsChecked == true,
                ShowChromatogram = chkChromatogram.IsChecked == true,
                ShowLibrarySearch = chkLibrarySearch.IsChecked == true,

                LogoImage = LoadLogoBytes(),
                ChromatogramImage = ForensicContext?.ChromatogramImage,
                SpectrumImage = ForensicContext?.SpectrumImage,
            };

            foreach (var row in Results)
            {
                data.ResultRows.Add(new[] { row.Target, row.Status, row.Confidence, row.Remarks });
            }

            return data;
        }

        private static byte[] LoadLogoBytes()
        {
            string[] logoPossiblePaths =
            {
                Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "Icons", "Perspectives", "MT_logo_12x4_wb_pp-scaled.png"),
                Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "ChromExplorer.Assets", "Icons", "Perspectives", "MT_logo_12x4_wb_pp-scaled.png"),
            };

            foreach (var path in logoPossiblePaths)
            {
                if (File.Exists(path))
                    return File.ReadAllBytes(path);
            }

            return null;
        }

        private void CloseOverlay()
        {
            if (RegionManager == null || !RegionManager.Regions.ContainsRegionWithName(RegionNames.OverContentRegion))
                return;

            var region = RegionManager.Regions[RegionNames.OverContentRegion];
            if (region.Views.Contains(this))
                region.Remove(this);
        }
    }
